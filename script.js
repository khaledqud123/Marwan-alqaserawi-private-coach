function translatePage(language) {

    const selectedLanguage =
        language === "ar" ? "ar" : "en";

    const dictionary =
        translations[selectedLanguage];

    document.documentElement.lang =
        selectedLanguage;

    document.documentElement.dir =
        selectedLanguage === "ar"
            ? "rtl"
            : "ltr";

    document.body.classList.toggle(
        "rtl",
        selectedLanguage === "ar"
    );

    document
        .querySelectorAll("[data-i18n]")
        .forEach((element) => {

            const key =
                element.dataset.i18n;

            const value =
                getTranslationValue(
                    dictionary,
                    key
                );

            if (value !== undefined) {
                element.innerHTML = value;
            }

        });

    document
        .querySelectorAll(".language-btn")
        .forEach((button) => {

            button.classList.toggle(
                "active",
                button.dataset.lang === selectedLanguage
            );

        });

    document
        .querySelectorAll(".mobile-language-btn")
        .forEach((button) => {

            button.classList.toggle(
                "active",
                button.dataset.lang === selectedLanguage
            );

        });

    document.title =
        selectedLanguage === "ar"
            ? "مروان القصراوي | مدرب تطوير الأداء"
            : "Marwan Alqaserawi | Performance Coach";

    localStorage.setItem(
        STORAGE_KEY,
        selectedLanguage
    );

    requestAnimationFrame(() => {
        refreshRevealElements();
    });

}


