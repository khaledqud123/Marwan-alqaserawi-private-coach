/* =========================================================
   MOBILE MENU
========================================================= */

function initializeMobileMenu() {

    const toggle =
        document.getElementById("menuToggle");

    const menu =
        document.getElementById("mobileMenu");

    if (!toggle || !menu) {
        return;
    }

    function openMenu() {

        menu.classList.add("open");
        toggle.classList.add("active");

        toggle.setAttribute(
            "aria-expanded",
            "true"
        );

        document.body.classList.add(
            "menu-open"
        );

    }

    function closeMenu() {

        menu.classList.remove("open");
        toggle.classList.remove("active");

        toggle.setAttribute(
            "aria-expanded",
            "false"
        );

        document.body.classList.remove(
            "menu-open"
        );

    }

    toggle.addEventListener(
        "click",
        () => {

            const isOpen =
                menu.classList.contains("open");

            if (isOpen) {
                closeMenu();
            } else {
                openMenu();
            }

        }
    );

    menu
        .querySelectorAll("a")
        .forEach((link) => {

            link.addEventListener(
                "click",
                closeMenu
            );

        });

    document.addEventListener(
        "keydown",
        (event) => {

            if (
                event.key === "Escape" &&
                menu.classList.contains("open")
            ) {
                closeMenu();
            }

        }
    );

}


/* =========================================================
   NAVBAR SCROLL
========================================================= */

function initializeNavbar() {

    const navbar =
        document.getElementById("navbar");

    if (!navbar) {
        return;
    }

    let lastScrollY =
        window.scrollY;

    function updateNavbar() {

        const currentScroll =
            window.scrollY;

        navbar.classList.toggle(
            "scrolled",
            currentScroll > 70
        );

        if (
            currentScroll > lastScrollY &&
            currentScroll > 150
        ) {

            navbar.classList.add(
                "nav-hidden"
            );

        } else {

            navbar.classList.remove(
                "nav-hidden"
            );

        }

        lastScrollY =
            currentScroll;

    }

    window.addEventListener(
        "scroll",
        updateNavbar,
        { passive: true }
    );

    updateNavbar();

}


/* =========================================================
   REVEAL ANIMATIONS
========================================================= */

let revealObserver;

function refreshRevealElements() {

    const elements =
        document.querySelectorAll(".reveal");

    if (!revealObserver) {
        return;
    }

    elements.forEach((element) => {

        if (
            element.classList.contains("visible")
        ) {
            return;
        }

        revealObserver.observe(element);

    });

}


function initializeReveal() {

    if (
        !("IntersectionObserver" in window)
    ) {

        document
            .querySelectorAll(".reveal")
            .forEach((element) => {

                element.classList.add(
                    "visible"
                );

            });

        return;

    }

    revealObserver =
        new IntersectionObserver(
            (entries, observer) => {

                entries.forEach((entry) => {

                    if (!entry.isIntersecting) {
                        return;
                    }

                    entry.target.classList.add(
                        "visible"
                    );

                    observer.unobserve(
                        entry.target
                    );

                });

            },
            {
                threshold: 0.12,
                rootMargin: "0px 0px -60px 0px"
            }
        );

    refreshRevealElements();

}


/* =========================================================
   COUNTERS
========================================================= */

function initializeCounters() {

    const counters =
        document.querySelectorAll(
            "[data-count]"
        );

    if (!counters.length) {
        return;
    }

    if (
        !("IntersectionObserver" in window)
    ) {

        counters.forEach((counter) => {

            counter.textContent =
                counter.dataset.count;

        });

        return;

    }

    const counterObserver =
        new IntersectionObserver(
            (entries, observer) => {

                entries.forEach((entry) => {

                    if (!entry.isIntersecting) {
                        return;
                    }

                    const counter =
                        entry.target;

                    animateCounter(
                        counter,
                        Number(counter.dataset.count)
                    );

                    observer.unobserve(
                        counter
                    );

                });

            },
            {
                threshold: 0.7
            }
        );

    counters.forEach((counter) => {

        counterObserver.observe(
            counter
        );

    });

}


function animateCounter(element, target) {

    const duration =
        target >= 100
            ? 1700
            : 1300;

    const startTime =
        performance.now();

    function update(currentTime) {

        const elapsed =
            currentTime - startTime;

        const progress =
            Math.min(
                elapsed / duration,
                1
            );

        const eased =
            1 -
            Math.pow(
                1 - progress,
                4
            );

        element.textContent =
            Math.floor(
                target * eased
            );

        if (progress < 1) {

            requestAnimationFrame(
                update
            );

        } else {

            element.textContent =
                target;

        }

    }

    requestAnimationFrame(update);

}


/* =========================================================
   PARALLAX
========================================================= */

function initializeParallax() {

    const targets =
        document.querySelectorAll(
            ".hero-image, .hero-video, .statement-image img"
        );

    if (
        !targets.length ||
        window.matchMedia(
            "(prefers-reduced-motion: reduce)"
        ).matches
    ) {
        return;
    }

    let ticking = false;

    function updateParallax() {

        const viewportHeight =
            window.innerHeight;

        targets.forEach((element) => {

            const rect =
                element.getBoundingClientRect();

            if (
                rect.bottom < 0 ||
                rect.top > viewportHeight
            ) {
                return;
            }

            const center =
                rect.top +
                rect.height / 2;

            const offset =
                (center - viewportHeight / 2) *
                -0.035;

            element.style.transform =
                `translate3d(0, ${offset}px, 0) scale(1.04)`;

        });

        ticking = false;

    }

    function requestUpdate() {

        if (ticking) {
            return;
        }

        ticking = true;

        requestAnimationFrame(
            updateParallax
        );

    }

    window.addEventListener(
        "scroll",
        requestUpdate,
        { passive: true }
    );

    window.addEventListener(
        "resize",
        requestUpdate
    );

    requestUpdate();

}


/* =========================================================
   MAGNETIC BUTTONS
========================================================= */

function initializeMagneticButtons() {

    const buttons =
        document.querySelectorAll(".magnetic");

    if (
        window.matchMedia(
            "(hover: none)"
        ).matches
    ) {
        return;
    }

    buttons.forEach((button) => {

        button.addEventListener(
            "mousemove",
            (event) => {

                const rect =
                    button.getBoundingClientRect();

                const x =
                    event.clientX -
                    rect.left -
                    rect.width / 2;

                const y =
                    event.clientY -
                    rect.top -
                    rect.height / 2;

                button.style.transform =
                    `translate(${x * 0.18}px, ${y * 0.18}px)`;

            }
        );

        button.addEventListener(
            "mouseleave",
            () => {

                button.style.transform = "";

            }
        );

    });

}


/* =========================================================
   CUSTOM CURSOR
========================================================= */

function initializeCursor() {

    const dot =
        document.getElementById("cursorDot");

    const follower =
        document.getElementById("cursorFollower");

    if (!dot || !follower) {
        return;
    }

    if (
        window.matchMedia(
            "(hover: none)"
        ).matches
    ) {
        return;
    }

    let mouseX = 0;
    let mouseY = 0;

    let followerX = 0;
    let followerY = 0;

    document.addEventListener(
        "mousemove",
        (event) => {

            mouseX =
                event.clientX;

            mouseY =
                event.clientY;

            dot.style.left =
                `${mouseX}px`;

            dot.style.top =
                `${mouseY}px`;

        }
    );

    function animateCursor() {

        followerX +=
            (mouseX - followerX) *
            0.16;

        followerY +=
            (mouseY - followerY) *
            0.16;

        follower.style.left =
            `${followerX}px`;

        follower.style.top =
            `${followerY}px`;

        requestAnimationFrame(
            animateCursor
        );

    }

    animateCursor();

    const hoverTargets =
        document.querySelectorAll(
            "a, button, .program-card, .instagram-item"
        );

    hoverTargets.forEach((element) => {

        element.addEventListener(
            "mouseenter",
            () => {

                document.body.classList.add(
                    "cursor-hover"
                );

            }
        );

        element.addEventListener(
            "mouseleave",
            () => {

                document.body.classList.remove(
                    "cursor-hover"
                );

            }
        );

    });

}


/* =========================================================
   PROGRAM CARD 3D TILT
========================================================= */

function initializeCardTilt() {

    if (
        window.matchMedia(
            "(hover: none)"
        ).matches
    ) {
        return;
    }

    const cards =
        document.querySelectorAll(
            "[data-tilt]"
        );

    cards.forEach((card) => {

        card.addEventListener(
            "mousemove",
            (event) => {

                const rect =
                    card.getBoundingClientRect();

                const x =
                    event.clientX -
                    rect.left;

                const y =
                    event.clientY -
                    rect.top;

                const centerX =
                    rect.width / 2;

                const centerY =
                    rect.height / 2;

                const rotateX =
                    ((y - centerY) / centerY) *
                    -3;

                const rotateY =
                    ((x - centerX) / centerX) *
                    3;

                card.style.transform =
                    `perspective(1200px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) scale3d(1.015,1.015,1.015)`;

            }
        );

        card.addEventListener(
            "mouseleave",
            () => {

                card.style.transform = "";

            }
        );

    });

}


/* =========================================================
   SMOOTH ANCHOR SCROLL
========================================================= */

function initializeSmoothScroll() {

    document
        .querySelectorAll('a[href^="#"]')
        .forEach((link) => {

            link.addEventListener(
                "click",
                (event) => {

                    const href =
                        link.getAttribute("href");

                    if (
                        !href ||
                        href === "#"
                    ) {
                        return;
                    }

                    const target =
                        document.querySelector(href);

                    if (!target) {
                        return;
                    }

                    event.preventDefault();

                    const navbar =
                        document.getElementById("navbar");

                    const offset =
                        navbar
                            ? navbar.offsetHeight
                            : 0;

                    const targetPosition =
                        target.getBoundingClientRect().top +
                        window.scrollY -
                        offset;

                    window.scrollTo({
                        top: targetPosition,
                        behavior: "smooth"
                    });

                }
            );

        });

}


