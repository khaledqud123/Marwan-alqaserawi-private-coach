/* =========================================================
   HERO VIDEO
========================================================= */

function initializeHeroVideo() {

    const video =
        document.getElementById("heroVideo");

    if (!video) {
        return;
    }

    const fallback =
        document.querySelector(".hero-image");

    const showVideo = () => {

        video.classList.add("playing");
        video.classList.remove("error");

        if (fallback) {
            fallback.style.opacity = "0";
        }

    };

    const showFallback = () => {

        video.classList.remove("playing");
        video.classList.add("error");

        if (fallback) {
            fallback.style.opacity = "1";
        }

    };

    video.muted = true;

    video.setAttribute(
        "muted",
        ""
    );

    video.setAttribute(
        "playsinline",
        ""
    );

    video.setAttribute(
        "webkit-playsinline",
        ""
    );

    video.addEventListener(
        "playing",
        showVideo
    );

    video.addEventListener(
        "error",
        showFallback
    );

    /*
       IMPORTANT:
       Do not treat an autoplay rejection as a
       broken video. Safari/iPad can reject the
       initial play request even when the video
       itself is perfectly valid.
    */

    const attemptPlay = () => {

        if (
            video.readyState >= 2
        ) {

            const playPromise =
                video.play();

            if (
                playPromise &&
                typeof playPromise.catch === "function"
            ) {

                playPromise
                    .then(showVideo)
                    .catch(() => {
                        /*
                           Ignore autoplay rejection.
                           The video remains available and
                           Safari can start it when allowed.
                        */
                    });

            }

        }

    };

    video.addEventListener(
        "loadeddata",
        attemptPlay,
        { once: true }
    );

    video.addEventListener(
        "canplay",
        attemptPlay,
        { once: true }
    );

    /*
       If the video is already ready when this
       function runs, try immediately.
    */

    attemptPlay();

}


